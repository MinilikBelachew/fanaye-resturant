/**
 * Searches keywords to find the most relevant preset given user typing.
 */
export function findMatchingPreset(query: string): InventoryPreset | null {
    const q = query.trim().toLowerCase();
    if (!q || q.length < 2) return null;

    // Exact name match first
    const exact = INVENTORY_PRESETS.find(
        p => p.name.toLowerCase() === q || p.id === q,
    );
    if (exact) return exact;

    // Keyword match
    for (const preset of INVENTORY_PRESETS) {
        if (
            preset.keywords.some(
                k =>
                    k.toLowerCase() === q ||
                    k.toLowerCase().includes(q) ||
                    q.includes(k.toLowerCase()),
            )
        ) {
            return preset;
        }
    }
    return null;
}

/**
 * Resolves an item image from explicit imageUrl or smart name lookup.
 */
export function resolveItemImage(
    imageUrl?: string | null,
    name?: string,
): string | null {
    if (imageUrl && imageUrl.trim()) {
        return imageUrl.trim();
    }
    if (name) {
        const match = findMatchingPreset(name);
        if (match) return match.imageUrl;
    }
    return null;
}
